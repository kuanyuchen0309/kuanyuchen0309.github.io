/* ============================================================================
   xudc.org —— 深色模式的"防闪烁"脚本
   ----------------------------------------------------------------------------
   【它为什么必须单独一个文件、而且必须放在 <head> 里、而且不能加 defer/async】

   浏览器画页面是这样的：先读到 <head>，把 HTML 结构搭出来，然后按 CSS
   上色，第一帧就画出来了。放在 <body> 末尾的脚本要等页面画完之后才跑。

   如果读取"用户选过深色还是浅色"这件事放到末尾去做，就会出现：
     第 1 帧 → 亮白   （因为还没人告诉 CSS 要深色）
     第 2 帧 → 变黑   （脚本跑完了）
   每次打开、每次点进新文章，都会白闪一下。这很难看。

   所以：把这段极短的代码放在 <head>，它在浏览器画第一帧之前就执行完，
   直接把 data-theme 写好，CSS 一上来就按深色上色，一次都不闪。

   ⚠️ 因此这个文件里不要写任何"等页面加载完"的代码、也不要做别的事。
      其他所有交互都在 js/app.js 里。
   ============================================================================ */
(function () {
  "use strict";

  const KEY = "xudc-theme";
  let saved = null;

  try {
    saved = window.localStorage.getItem(KEY);
  } catch (e) {
    /* 浏览器的隐私模式或用户禁用了网站存储时会抛错。
       这不是问题：读不到就当"没选过"，继续跟随系统。 */
    saved = null;
  }

  /* 只在用户【手动选过】的时候才写 data-theme。
     没选过就不写 —— 这样 CSS 里的 @media (prefers-color-scheme: dark)
     会接管，页面自动跟随系统，而且系统主题一改页面立刻跟着变。 */
  if (saved === "dark" || saved === "light") {
    document.documentElement.setAttribute("data-theme", saved);
  }
})();
